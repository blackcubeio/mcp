namespace Blackcube\Mcp\Tests\Integration;

use Blackcube\Mcp\Mcp\Tools\ElasticSchema\Create;
use Blackcube\Mcp\Mcp\Tools\ElasticSchema\Index;
use Blackcube\Mcp\Mcp\Tools\ElasticSchema\Update;
use Blackcube\Mcp\Tests\Support\DatabaseCestTrait;
use Blackcube\Mcp\Tests\Support\IntegrationTester;
use Psr\Log\NullLogger;

/**
 * Real round-trip for the elasticSchema.* tools: each write goes through the
 * actual tool (save), is checked against the real database row, and read back
 * through the read tool — proving mcp output, DB state and re-read agree (ISO).
 * No mock, no stub: a real MySQL schema (DatabaseCestTrait) and the real
 * ActiveRecord. The id is generated by the database and recovered from the
 * create result; the JSON-Schema survives encode (write) / decode (read).
 *
 * @copyright 2010-2026 Blackcube - Philippe Gaultier
 * @license https://www.blackcube.io/license
 * @link https://www.blackcube.io
 */
class ElasticSchemaRoundTripCest
{
    use DatabaseCestTrait;

    public function testCreateUpdateRoundTrip(IntegrationTester $I): void
    {
        $I->wantTo('round-trip an elastic schema through the mcp tools: save -> DB -> read, ISO');

        $schema = [
            '$schema' => 'http://json-schema.org/draft-07/schema#',
            'type' => 'object',
            'properties' => [
                'title' => [
                    'type' => 'string',
                ],
            ],
            'required' => [
                'title',
            ],
        ];
        $created = (new Create(new NullLogger()))->handle('RoundTrip', 'common', $schema, null, 'title => Title', true);
        $I->assertIsArray($created);
        $id = $created['id'];
        $I->assertIsInt($id);
        $I->assertGreaterThan(0, $id);

        $expected = [
            'id' => $id,
            'name' => 'RoundTrip',
            'kind' => 'common',
            'schema' => $schema,
            'mdMapping' => 'title => Title',
            'builtin' => false,
            'hidden' => false,
            'active' => true,
        ];
        $I->assertSame($expected, $created);

        $storedSchema = $this->db
            ->createCommand('SELECT name, kind, `schema`, mdMapping, active FROM elasticSchemas WHERE id = ' . (int) $id)
            ->queryOne();
        $I->assertSame('RoundTrip', $storedSchema['name']);
        $I->assertSame('common', $storedSchema['kind']);
        $I->assertSame(json_encode($schema, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), $storedSchema['schema']);
        $I->assertSame('title => Title', $storedSchema['mdMapping']);
        $I->assertSame(1, (int) $storedSchema['active']);

        $listed = (new Index())->handle();
        $I->assertContains($created, $listed['items']);

        $schemaUpdated = [
            '$schema' => 'http://json-schema.org/draft-07/schema#',
            'type' => 'object',
            'properties' => [
                'title' => [
                    'type' => 'string',
                ],
                'body' => [
                    'type' => 'string',
                ],
            ],
            'required' => [
                'title',
                'body',
            ],
        ];
        $updated = (new Update(new NullLogger()))->handle($id, 'RoundTripEdited', null, $schemaUpdated, null, null, false);
        $expectedUpdated = [
            'id' => $id,
            'name' => 'RoundTripEdited',
            'kind' => 'common',
            'schema' => $schemaUpdated,
            'mdMapping' => 'title => Title',
            'builtin' => false,
            'hidden' => false,
            'active' => false,
        ];
        $I->assertSame($expectedUpdated, $updated);

        $storedSchema = $this->db
            ->createCommand('SELECT name, kind, `schema`, mdMapping, active FROM elasticSchemas WHERE id = ' . (int) $id)
            ->queryOne();
        $I->assertSame('RoundTripEdited', $storedSchema['name']);
        $I->assertSame('common', $storedSchema['kind']);
        $I->assertSame(json_encode($schemaUpdated, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), $storedSchema['schema']);
        $I->assertSame('title => Title', $storedSchema['mdMapping']);
        $I->assertSame(0, (int) $storedSchema['active']);

        $listed = (new Index())->handle();
        $I->assertContains($updated, $listed['items']);
    }
}
