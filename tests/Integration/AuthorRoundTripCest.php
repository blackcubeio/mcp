namespace Blackcube\Mcp\Tests\Integration;

use Blackcube\Mcp\Mcp\Tools\Author\Create;
use Blackcube\Mcp\Mcp\Tools\Author\Index;
use Blackcube\Mcp\Mcp\Tools\Author\Update;
use Blackcube\Mcp\Tests\Support\DatabaseCestTrait;
use Blackcube\Mcp\Tests\Support\IntegrationTester;
use Psr\Log\NullLogger;

/**
 * Real round-trip for the author.* tools: each write goes through the actual
 * tool (save), is checked against the real database row, and read back through
 * the read tool — proving mcp output, DB state and re-read agree (ISO). No mock,
 * no stub: a real MySQL schema (DatabaseCestTrait) and the real ActiveRecord.
 * The id is generated by the database and recovered from the create result.
 *
 * @copyright 2010-2026 Blackcube - Philippe Gaultier
 * @license https://www.blackcube.io/license
 * @link https://www.blackcube.io
 */
class AuthorRoundTripCest
{
    use DatabaseCestTrait;

    public function testCreateUpdateRoundTrip(IntegrationTester $I): void
    {
        $I->wantTo('round-trip an author through the mcp tools: save -> DB -> read, ISO');

        $created = (new Create(new NullLogger()))->handle(
            'Ada',
            'Lovelace',
            'ada@example.com',
            'Mathematician',
            'Analytical Engine Company',
            "Mathematics\nComputing",
            'https://profiles.example.com/ada',
            'https://example.com/ada',
            'https://example.com/ada.png',
            true,
        );
        $I->assertIsArray($created);
        $id = $created['id'];
        $I->assertIsInt($id);
        $I->assertGreaterThan(0, $id);

        $expected = [
            'id' => $id,
            'firstname' => 'Ada',
            'lastname' => 'Lovelace',
            'email' => 'ada@example.com',
            'jobTitle' => 'Mathematician',
            'worksFor' => 'Analytical Engine Company',
            'knowsAbout' => "Mathematics\nComputing",
            'sameAs' => 'https://profiles.example.com/ada',
            'url' => 'https://example.com/ada',
            'image' => 'https://example.com/ada.png',
            'active' => true,
        ];
        $I->assertSame($expected, $created);

        $storedAuthor = $this->db
            ->createCommand('SELECT firstname, lastname, email, jobTitle, worksFor, knowsAbout, sameAs, url, image, active FROM authors WHERE id = ' . (int) $id)
            ->queryOne();
        $I->assertSame('Ada', $storedAuthor['firstname']);
        $I->assertSame('Lovelace', $storedAuthor['lastname']);
        $I->assertSame('ada@example.com', $storedAuthor['email']);
        $I->assertSame('Mathematician', $storedAuthor['jobTitle']);
        $I->assertSame('Analytical Engine Company', $storedAuthor['worksFor']);
        $I->assertSame("Mathematics\nComputing", $storedAuthor['knowsAbout']);
        $I->assertSame('https://profiles.example.com/ada', $storedAuthor['sameAs']);
        $I->assertSame('https://example.com/ada', $storedAuthor['url']);
        $I->assertSame('https://example.com/ada.png', $storedAuthor['image']);
        $I->assertSame(1, (int) $storedAuthor['active']);

        $listed = (new Index())->handle();
        $I->assertContains($created, $listed['items']);

        $updated = (new Update(new NullLogger()))->handle($id, null, 'King', null, 'Countess of Lovelace', null, null, null, null, null, false);
        $expectedUpdated = [
            'id' => $id,
            'firstname' => 'Ada',
            'lastname' => 'King',
            'email' => 'ada@example.com',
            'jobTitle' => 'Countess of Lovelace',
            'worksFor' => 'Analytical Engine Company',
            'knowsAbout' => "Mathematics\nComputing",
            'sameAs' => 'https://profiles.example.com/ada',
            'url' => 'https://example.com/ada',
            'image' => 'https://example.com/ada.png',
            'active' => false,
        ];
        $I->assertSame($expectedUpdated, $updated);

        $storedAuthor = $this->db
            ->createCommand('SELECT firstname, lastname, jobTitle, active FROM authors WHERE id = ' . (int) $id)
            ->queryOne();
        $I->assertSame('Ada', $storedAuthor['firstname']);
        $I->assertSame('King', $storedAuthor['lastname']);
        $I->assertSame('Countess of Lovelace', $storedAuthor['jobTitle']);
        $I->assertSame(0, (int) $storedAuthor['active']);

        $listed = (new Index())->handle();
        $I->assertContains($updated, $listed['items']);
    }
}
